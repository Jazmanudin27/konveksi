for (const line of lines) {
  const parts = line.split("\t");
  if (parts.length < 4) continue;
  const sku = parts[0].trim();
  const kategori = parts[1].trim().toUpperCase();
  const varian = parts[2].trim();
  const ukuran = parts[3].trim();

  parsedProducts.push({
    sku,
    namaProduk: sku,
    kategori,
    varian,
    ukuran,
    stok: 0,
    harga: 0,
    hpp: 0,
    status: 'Aktif'
  });

  if (!categoriesMap.has(kategori)) {
    categoriesMap.set(kategori, 0);
  }
  categoriesMap.set(kategori, categoriesMap.get(kategori) + 1);
}

